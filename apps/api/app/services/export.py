"""Export renderers for the Structured Audit Report (PRD FR-18, §22).

Renders an ``ega_schemas.report.AuditReport`` to self-contained Markdown, HTML,
JSON and RFC-4180 CSV payloads.

Conventions:
- CSV uses the stdlib ``csv`` module with ``QUOTE_MINIMAL`` and ``\\r\\n`` row
  terminators (RFC-4180). Embedded newlines inside quoted fields are legal and
  round-trip through ``csv.reader``.
- ``render_json`` is canonical: ``exclude_none=False``, ``indent=2``, declaration
  key order (``sort_keys=False``), UTF-8 (``ensure_ascii=False``).
- HTML is one self-contained file: inline CSS only, no scripts, no external
  resources, CSP ``default-src 'none'`` meta tag; every dynamic value is passed
  through ``html.escape``.
- The Markdown and HTML renderers walk the same section/block model, so both
  always contain the same 18 PRD FR-18 sections in the same order.
"""

