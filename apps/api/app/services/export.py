# ------------------------------------------------------------- block model ---


def _p(text: str) -> dict:
    return {"kind": "p", "text": str(text)}


def _ul(items: list) -> dict:
    return {"kind": "ul", "items": [str(i) for i in items]}


def _quote(text: str) -> dict:
    return {"kind": "quote", "text": str(text)}


def _table(headers: list, rows: list) -> dict:
    return {"kind": "table", "headers": [str(h) for h in headers], "rows": [list(r) for r in rows]}


def _h4(text: str) -> dict:
    return {"kind": "h4", "text": str(text)}


def _h5(text: str) -> dict:
    return {"kind": "h5", "text": str(text)}


def _val(value) -> str:
    return _EMPTY if value is None else str(value)


def _enum(value) -> str:
    if value is None:
        return _EMPTY
    return value.value if hasattr(value, "value") else str(value)


def _issue_text(issue) -> str:
    """Gate issue lists now accept str | GateIssue; normalize to display text."""
    if isinstance(issue, str):
        return issue
    for attr in ("message", "title", "detail", "issue_id"):
        value = getattr(issue, attr, None)
        if value:
            return str(value)
    return str(issue)


def _composite(report: AuditReport):
    if report.composite_avr is not None:
        return report.composite_avr
    return getattr(report.scores, "avr", None)


def _score_profile_name(report: AuditReport) -> str:
    name = getattr(report.scores, "profile_name", None)
    return str(name or getattr(report, "profile_name", "default"))


def _swot_list(report: AuditReport, key: str) -> list[str]:
    swot = report.swot
    if isinstance(swot, dict):
        return [str(x) for x in swot.get(key, []) or []]
    return [str(x) for x in getattr(swot, key, []) or []]


def _source_label(source) -> str:
    """Sources may be SourceCitation (verification_state) or EvidenceSource (label)."""
    label = getattr(source, "label", None)
    if label is not None:
        return _enum(label)
    return _val(getattr(source, "verification_state", None))


def _report_findings(report: AuditReport) -> list[Finding]:
    """All Finding objects known to the report, deduped by finding_id."""
    seen: dict[str, Finding] = {}
    groups = [report.findings, report.recommendations, report.passage_findings]
    for group in groups:
        for finding in group:
            seen.setdefault(finding.finding_id, finding)
    return list(seen.values())


def _claim_source(report: AuditReport, claim: Claim):
    by_id = {}
    for s in list(report.sources) + list(report.evidence_sources):
        by_id.setdefault(s.source_id, s)
    for sid in claim.evidence_source_ids:
        if sid in by_id:
            return by_id[sid]
    return None


# --------------------------------------------------------- section builders ---


def _s01(report: AuditReport) -> list[dict]:
    m = report.audit_metadata
    rows = [
        ["Project ID", m.project_id],
        ["Run ID", m.run_id],
        ["Page type", _enum(m.page_type)],
        ["Page type source", _val(getattr(m, "page_type_source", None))],
        ["Language", m.language],
        ["Central entity", _val(m.central_entity)],
        ["Primary intent", _enum(m.primary_intent)],
        ["Created at", m.created_at],
        ["Content hash (source)", m.content_hash],
        ["Score profile version", m.score_profile_version],
        ["Provider model", _val(m.provider_model)],
        ["Context packs", ", ".join(m.context_pack_versions) or _EMPTY],
    ]
    assumptions = list(m.assumptions) or ["None recorded."]
    return [
        _p("Page purpose, provenance and assumptions for this audit run."),
        _table(["Field", "Value"], rows),
        _p("**Assumptions:**"),
        _ul(assumptions),
    ]


def _s02(report: AuditReport) -> list[dict]:
    status = _enum(report.gate.status)
    sentence = f"Gate status: **{status}** — {_GATE_TAIL.get(status, 'see gate details in section 4.')}"
    composite = _composite(report)
    if composite is not None:
        sentence += (
            f" Composite AVR: {composite:.1f}/10"
            f" (score profile {report.audit_metadata.score_profile_version})."
        )
    strengths = _swot_list(report, "strengths")[:3] or ["None recorded."]
    ranked = sorted(
        _report_findings(report), key=lambda f: f.priority_score, reverse=True
    )[:3]
    gaps = [f"{f.title} [{f.severity.value}]" for f in ranked] or ["None recorded."]
    return [
        _p(sentence),
        _p("**Top strengths:**"),
        _ul(strengths),
        _p("**Top gaps:**"),
        _ul(gaps),
    ]


def _s03(report: AuditReport) -> list[dict]:
    rows = []
    for key, comp in report.scores.items():
        val = getattr(comp, "value", None) if not isinstance(comp, dict) else comp.get("value")
        conf = getattr(comp, "confidence", None) if not isinstance(comp, dict) else comp.get("confidence")
        weight = getattr(comp, "weight", None) if not isinstance(comp, dict) else comp.get("weight")
        rationale = getattr(comp, "rationale", None) if not isinstance(comp, dict) else comp.get("rationale")
        val_str = f"{val:.1f}" if val is not None else _EMPTY
        conf_str = _enum(conf)
        weight_str = f"{weight:g}" if weight is not None else _EMPTY
        rationale_str = rationale or _EMPTY
        rows.append(
            [
                key,
                val_str,
                conf_str,
                weight_str,
                rationale_str,
            ]
        )
    blocks = [
        _table(
            ["Component", "Value", "Confidence", "Weight", "Rationale"],
            rows,
        )
    ]
    composite = _composite(report)
    if composite is not None:
        blocks.append(_p(f"Composite AVR: {composite:.1f}/10"))
    blocks.append(_p(SCORE_HEURISTIC_DISCLAIMER))
    blocks.append(
        _p(
            f"Profile: {_score_profile_name(report)} — score profile version:"
            f" {report.audit_metadata.score_profile_version}"
        )
    )
    return blocks


def _s04(report: AuditReport) -> list[dict]:
    gate = report.gate
    blocks: list[dict] = []
    if _enum(gate.status) == "fail":
        criticals = [_issue_text(i) for i in gate.critical_issues] or ["(none recorded)"]
        text = "**NOT PUBLISHABLE AS-IS**\n\nCritical gate failures:\n\n" + "\n".join(
            f"- {issue}" for issue in criticals
        )
        blocks.append(_quote(text))
    else:
        blocks.append(
            _p(f"No critical gate failures. Current gate status: {_enum(gate.status)}.")
        )
    if gate.noncritical_issues:
        blocks.append(_p("**Non-critical gate issues:**"))
        blocks.append(_ul([_issue_text(i) for i in gate.noncritical_issues]))
    return blocks


def _s05(report: AuditReport) -> list[dict]:
    rows = []
    present: set[str] = set()
    for e in report.entities:
        present.add(_enum(e.kind))
        rows.append(
            [
                e.canonical_name,
                _enum(e.kind),
                "yes" if e.is_central else "no",
                f"{e.salience:.2f}",
                _enum(e.confidence),
                str(len(e.occurrences)),
                ", ".join(e.aliases) or _EMPTY,
            ]
        )
    missing = list(report.entity_missing_groups) or [
        g for g in _CORE_ENTITY_GROUPS if g not in present
    ]
    missing = missing or ["none"]
    return [
        _table(
            ["Entity", "Kind", "Central", "Salience", "Confidence", "Occurrences", "Aliases"],
            rows,
        )
        if rows
        else _p("No entities recorded."),
        _p("Missing groups: " + ", ".join(missing) + "."),
    ]


def _s06(report: AuditReport) -> list[dict]:
    rows = []
    for r in report.eav_rows:
        evidence = r.evidence_excerpt or r.notes or _EMPTY
        rows.append(
            [r.entity_name, r.attribute, _val(r.value), _enum(r.status), evidence]
        )
    if not rows:
        return [_p("No entity-attribute-value rows recorded.")]
    return [
        _table(
            ["Entity", "Attribute", "Value found", "Status", "Evidence/fix"], rows
        )
    ]


def _s07(report: AuditReport) -> list[dict]:
    if not report.triples:
        return [_p("No semantic triples recorded.")]
    blocks: list[dict] = []
    seen: list[str] = []
    for t in report.triples:
        ttype = _enum(t.triple_type)
        if ttype not in seen:
            seen.append(ttype)
            rows = [
                [
                    x.subject,
                    x.predicate,
                    x.object_,
                    _enum(x.status),
                    x.evidence_excerpt or _EMPTY,
                ]
                for x in report.triples
                if _enum(x.triple_type) == ttype
            ]
            blocks.append(_h5(ttype))
            blocks.append(
                _table(["Subject", "Predicate", "Object", "Status", "Evidence excerpt"], rows)
            )
    return blocks


def _s08(report: AuditReport) -> list[dict]:
    coverage = {c.query_id: c for c in report.coverage_rows}
    rows = []
    for q in report.fanout:
        cov = coverage.get(q.query_id)
        if cov is None:
            cov_cell, gap = "not evaluated", _EMPTY
        else:
            cov_cell = f"{_enum(cov.status)} ({cov.coverage_score:.2f})"
            if cov.gap_reason:
                gap = cov.gap_reason
            elif cov.destination_page:
                gap = f"Destination: {cov.destination_page}"
            else:
                gap = _EMPTY
        rows.append(
            [
                q.query_text,
                _enum(q.intent),
                _enum(q.origin),
                _enum(q.source),
                str(q.importance),
                _enum(q.scope),
                cov_cell,
                gap,
            ]
        )
    counts = Counter(_enum(q.origin) for q in report.fanout)
    observed = counts.get("observed", 0)
    simulated = counts.get("simulated", 0)
    provenance = (
        f"Provenance summary: observed={observed}, simulated={simulated},"
        f" total={len(report.fanout)}."
    )
    fcs = report.scores.get("FCS")
    if fcs is not None and (
        fcs.observed_queries is not None or fcs.simulated_queries is not None
    ):
        provenance += (
            f" FCS inputs: observed_queries={_val(fcs.observed_queries)},"
            f" simulated_queries={_val(fcs.simulated_queries)}."
        )
    blocks = [_p(provenance)]
    if rows:
        blocks.append(
            _table(
                [
                    "Query",
                    "Intent",
                    "Origin",
                    "Source",
                    "Importance",
                    "Scope",
                    "Coverage",
                    "Gap / remedy",
                ],
                rows,
            )
        )
    else:
        blocks.append(_p("No fan-out queries recorded."))
    return blocks


def _s09(report: AuditReport) -> list[dict]:
    if not report.passage_findings:
        return [_p("No passage-level findings recorded.")]
    blocks: list[dict] = []
    for i, f in enumerate(report.passage_findings, 1):
        blocks.append(_h5(f"{i}. {f.title}"))
        blocks.append(
            _p(
                f"Severity: {_enum(f.severity)} · Category: {f.category} ·"
                f" Confidence: {_enum(f.confidence)} · Status: {_enum(f.status)}"
            )
        )
        excerpt = f.where.excerpt if f.where else None
        if excerpt:
            blocks.append(_p("**Excerpt:**"))
            blocks.append(_quote(excerpt))
        blocks.append(_p("**Issues:**"))
        blocks.append(_p(f.what or _EMPTY))
        blocks.append(_p("**Strengths:**"))
        strengths = getattr(f, "strengths", None) or []
        blocks.append(_p(", ".join(str(s) for s in strengths) if strengths else _EMPTY))
        blocks.append(_p("**Evidence:**"))
        blocks.append(_ul(list(f.evidence) or [_EMPTY]))
        if f.how and f.how.suggested_rewrite:
            blocks.append(_p(f"**Suggested rewrite:** {f.how.suggested_rewrite}"))
    return blocks


def _s10(report: AuditReport) -> list[dict]:
    if not report.claims:
        return [_p("No claims recorded.")]
    rows = []
    for c in report.claims:
        src = _claim_source(report, c)
        rows.append(
            [
                c.statement,
                _enum(c.risk_tier),
                _source_label(src) if src else _EMPTY,
                _enum(c.verification_state),
                (src.url if src and src.url else _EMPTY),
            ]
        )
    return [
        _table(
            ["Claim", "Risk", "Evidence label", "Verification", "Source URL"], rows
        )
    ]


def _lexicon_values(handoff: dict, keys: tuple[str, ...]) -> list[str]:
    for key in keys:
        if key in handoff:
            value = handoff[key]
            if isinstance(value, str):
                return [value]
            if isinstance(value, list):
                return [str(v) for v in value]
    return []


def _s11(report: AuditReport) -> list[dict]:
    include: list[str] = []
    replace: list[str] = []
    avoid: list[str] = []
    handoff = getattr(report, "writer_handoff", None)
    if isinstance(handoff, dict):
        lexicon = handoff.get("lexicon")
        if isinstance(lexicon, dict):
            handoff = {**lexicon, **handoff}
        include = _lexicon_values(handoff, ("include", "terms_to_include", "terms_include"))
        replace = _lexicon_values(handoff, ("replace", "terms_to_replace"))
        avoid = _lexicon_values(
            handoff, ("avoid", "terms_to_avoid", "banned", "banned_terms")
        )
    if not (include or replace or avoid):
        # Deterministic fallback derived from findings (title + category only).
        for f in _report_findings(report):
            hay = f"{f.title} {f.category}".lower()
            if "avoid" in hay or "banned" in hay:
                avoid.append(f.title)
            elif "replace" in hay:
                replace.append(f.title)
            elif "include" in hay:
                include.append(f.title)
    none = ["(none derived)"]
    return [
        _p("**Include:**"),
        _ul(include or none),
        _p("**Replace:**"),
        _ul(replace or none),
        _p("**Avoid:**"),
        _ul(avoid or none),
    ]


def _s12(report: AuditReport) -> list[dict]:
    bullets: list[str] = []
    for f in _report_findings(report):
        if "link" in f.category.lower() or "link" in f.title.lower():
            bullets.append(f"{f.title} — {f.what}")
    for row in report.coverage_rows:
        if row.destination_page:
            bullets.append(
                f"Query '{row.query_text}' → suggested destination: {row.destination_page}"
            )
    return [
        _p("Internal link suggestions:"),
        _ul(bullets or ["None recorded."]),
    ]


def _s13(report: AuditReport) -> list[dict]:
    typed = [
        f
        for f in _report_findings(report)
        if "page_type" in f.category.lower() or "page type" in f.title.lower()
    ]
    return [
        _p(f"Active page type: {_enum(report.audit_metadata.page_type)}."),
        _p("Page-type-specific issues:"),
        _ul([f.title for f in typed] or ["No page-type-specific issues recorded."]),
    ]


def _s14(report: AuditReport) -> list[dict]:
    swot = report.swot
    return [
        _h4("strengths"),
        _ul(list(swot.strengths) or ["None recorded."]),
        _h4("weaknesses"),
        _ul(list(swot.weaknesses) or ["None recorded."]),
        _h4("opportunities"),
        _ul(list(swot.opportunities) or ["None recorded."]),
        _h4("threats"),
        _ul(list(swot.threats) or ["None recorded."]),
    ]


def _where_text(f: Finding) -> str:
    if not f.where:
        return _EMPTY
    parts = []
    if f.where.section_id:
        parts.append(f"section {f.where.section_id}")
    if f.where.passage_id:
        parts.append(f"passage {f.where.passage_id}")
    if f.where.excerpt:
        parts.append(f'“{f.where.excerpt}”')
    return "; ".join(parts) or _EMPTY


def _why_text(f: Finding) -> str:
    if not f.why:
        return _EMPTY
    pairs = [
        ("layer", f.why.layer),
        ("intent/query", f.why.intent_or_query),
        ("entity", f.why.entity),
        ("attribute", f.why.attribute),
        ("EAV status", f.why.eav_status),
        ("rule", f.why.rule_id),
    ]
    return "; ".join(f"{k}: {v}" for k, v in pairs if v) or _EMPTY


def _how_text(f: Finding) -> str:
    if not f.how:
        return _EMPTY
    if f.how.suggested_rewrite:
        return f.how.suggested_rewrite
    if f.how.implementation_steps:
        return " → ".join(f.how.implementation_steps)
    return _EMPTY


def _verification_text(f: Finding) -> str:
    if f.how and f.how.verification_condition:
        return f.how.verification_condition
    return _EMPTY


def _s15(report: AuditReport) -> list[dict]:
    recs = sorted(
        report.recommendations, key=lambda f: f.priority_score, reverse=True
    )
    if not recs:
        return [_p("No recommendations recorded.")]
    blocks = [
        _p(
            "Recommendations ranked by Priority = (Impact × Confidence) / Effort"
            " (PRD §9.6); it is a prioritization heuristic, not a probability."
        )
    ]
    for i, f in enumerate(recs, 1):
        blocks.append(_h5(f"{i}. {f.title}"))
        blocks.append(_p(f"**What:** {f.what}"))
        blocks.append(_p(f"**Where:** {_where_text(f)}"))
        blocks.append(_p(f"**Why:** {_why_text(f)}"))
        blocks.append(_p(f"**How:** {_how_text(f)}"))
        blocks.append(_p(f"**Verification:** {_verification_text(f)}"))
        blocks.append(
            _p(
                f"**Priority:** {f.priority_score:.1f}"
                f" (impact {f.impact} × confidence {f.confidence_numeric}"
                f" / effort {f.effort}; severity {_enum(f.severity)};"
                f" status {_enum(f.status)})"
            )
        )
    return blocks


def _s16(report: AuditReport) -> list[dict]:
    items = []
    for entry in report.measurement_plan:
        if isinstance(entry, dict):
            items.append("; ".join(f"{k}: {v}" for k, v in entry.items()))
        else:
            items.append(str(entry))
    return [
        _p("Validation / measurement plan:"),
        _ul(items or ["None recorded."]),
    ]


def _s17(report: AuditReport) -> list[dict]:
    if not report.sources:
        return [_p("No sources recorded.")]
    created = report.audit_metadata.created_at
    rows = []
    for s in report.sources:
        access = getattr(s, "access_date", None) or created
        rows.append([s.title, _val(s.url), access, _source_label(s)])
    return [
        _p(
            "Access date falls back to the audit run creation date"
            f" ({created}) when the source record has none."
        ),
        _table(["Title", "URL", "Access date", "Verification"], rows),
    ]


def _s18(report: AuditReport) -> list[dict]:
    metadata = report.audit_metadata
    limitations = [str(x) for x in report.limitations] + list(metadata.warnings)
    technical = [f"Technical flag: {t}" for t in report.technical_flags]
    not_assessed: list[str] = [str(x) for x in report.not_assessed]
    for key, comp in report.scores.items():
        if _enum(comp.confidence) == "not_assessed":
            reason = f" — {comp.rationale}" if comp.rationale else ""
            not_assessed.append(f"Score {key}: not assessed{reason}")
    for c in report.claims:
        if _enum(c.verification_state) == "not_assessed":
            not_assessed.append(f"Claim: {c.statement}")
    if _enum(report.gate.status) == "not_assessed":
        not_assessed.append("Gate: not assessed")
    if _composite(report) is None:
        not_assessed.append("Composite AVR: not calculated")
    skipped = list(getattr(metadata, "skipped_stages", []) or [])
    for record in report.stage_records:
        if isinstance(record, dict) and str(record.get("status")) == "skipped":
            label = record.get("node") or record.get("label") or "unnamed stage"
            if label not in skipped:
                skipped.append(str(label))
    return [
        _p("**Limitations & warnings:**"),
        _ul(limitations + technical or ["None recorded."]),
        _p("**Not assessed items:**"),
        _ul(not_assessed or ["None recorded."]),
        _p("**Skipped stages:**"),
        _ul([str(s) for s in skipped] or ["None recorded."]),
    ]


