def render_csv_zip(report: AuditReport) -> bytes:
    """In-memory ZIP with findings.csv, entities.csv, eav.csv, fanout.csv, scores.csv, claims.csv."""
    files = (
        ("findings.csv", render_findings_csv(report)),
        ("entities.csv", render_entities_csv(report)),
        ("eav.csv", render_eav_csv(report)),
        ("fanout.csv", render_fanout_csv(report)),
        ("scores.csv", _render_scores_csv(report)),
        ("claims.csv", _render_claims_csv(report)),
    )
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for name, text in files:
            zf.writestr(name, text.encode("utf-8"))
    return buf.getvalue()


# ----------------------------------------------------------------- render ---


def _safe_filename(run_id: str) -> str:
    return re.sub(r"[^A-Za-z0-9._-]", "_", run_id) or "run"


def render(report: AuditReport, fmt: str) -> tuple[bytes, str, str]:
    """Render ``fmt`` → ``(payload, media_type, filename)``.

    ``csv`` returns the six-file CSV bundle as a ZIP (a single table cannot
    represent the whole report); media type is ``application/zip``.
    """
    key = (fmt or "").strip().lower()
    stem = f"audit-{_safe_filename(report.audit_metadata.run_id)}"
    if key == "markdown":
        return render_markdown(report).encode("utf-8"), "text/markdown", f"{stem}.md"
    if key == "html":
        return render_html(report).encode("utf-8"), "text/html", f"{stem}.html"
    if key == "json":
        return render_json(report), "application/json", f"{stem}.json"
    if key == "csv":
        return render_csv_zip(report), "application/zip", f"{stem}.csv.zip"
    raise ValueError(
        f"Unsupported export format {fmt!r}."
        f" Supported formats: {', '.join(SUPPORTED_FORMATS)}"
    )
