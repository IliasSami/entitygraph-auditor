# --------------------------------------------------------------- markdown ---


def _md_cell(value) -> str:
    text = _EMPTY if value is None else str(value)
    return text.replace("\r\n", " ").replace("\n", " ").replace("|", "\\|")


def _md_block(block: dict) -> str:
    kind = block["kind"]
    if kind == "p":
        return block["text"]
    if kind == "ul":
        return "\n".join(
            "- " + str(item).replace("\n", " ") for item in block["items"]
        )
    if kind == "quote":
        return "\n".join(
            ("> " + line) if line else ">" for line in block["text"].split("\n")
        )
    if kind == "table":
        head = "| " + " | ".join(_md_cell(h) for h in block["headers"]) + " |"
        sep = "|" + "|".join("---" for _ in block["headers"]) + "|"
        rows = [
            "| " + " | ".join(_md_cell(c) for c in row) + " |" for row in block["rows"]
        ]
        return "\n".join([head, sep, *rows])
    if kind == "h4":
        return "#### " + block["text"]
    if kind == "h5":
        return "##### " + block["text"]
    raise ValueError(f"Unknown block kind: {kind!r}")


def render_markdown(report: AuditReport) -> str:
    """Render the report as Markdown covering all 18 PRD FR-18 sections."""
    parts = ["\n".join(_header_lines(report))]
    for title, blocks in _sections(report):
        body = "\n\n".join(_md_block(b) for b in blocks)
        parts.append(f"## {title}\n\n{body}")
    return "\n\n".join(parts) + "\n"


