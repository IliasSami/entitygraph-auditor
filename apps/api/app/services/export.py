def _html_block(block: dict) -> str:
    kind = block["kind"]
    if kind == "p":
        return f"<p>{html_escape(block['text'])}</p>"
    if kind == "ul":
        items = "".join(
            f"<li>{html_escape(str(i)).replace(chr(10), '<br>')}</li>"
            for i in block["items"]
        )
        return f"<ul>{items}</ul>"
    if kind == "quote":
        lines = "<br>\n".join(
            html_escape(line) for line in block["text"].split("\n")
        )
        return f"<blockquote><p>{lines}</p></blockquote>"
    if kind == "table":
        head = "".join(f"<th>{html_escape(str(h))}</th>" for h in block["headers"])
        body = "".join(
            "<tr>"
            + "".join(f"<td>{html_escape(str(c))}</td>" for c in row)
            + "</tr>"
            for row in block["rows"]
        )
        return f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"
    if kind == "h4":
        return f"<h4>{html_escape(block['text'])}</h4>"
    if kind == "h5":
        return f"<h5>{html_escape(block['text'])}</h5>"
    raise ValueError(f"Unknown block kind: {kind!r}")


def render_html(report: AuditReport) -> str:
    """Render a self-contained, fully escaped HTML file (no scripts, CSP-default none)."""
    esc = html_escape
    m = report.audit_metadata
    status = _enum(report.gate.status)
    badge_text = status.upper()
    if status == "fail":
        badge_text += " — NOT PUBLISHABLE AS-IS"
    out = [
        "<!DOCTYPE html>",
        '<html lang="en">',
        "<head>",
        '<meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
        '<meta http-equiv="Content-Security-Policy"'
        ' content="default-src \'none\'; style-src \'unsafe-inline\'">',
        f"<title>{esc('EntityGraph Auditor Audit Report — ' + m.run_id)}</title>",
        f"<style>{_HTML_STYLE}</style>",
        "</head>",
        "<body>",
        "<h1>EntityGraph Auditor Audit Report</h1>",
        '<div class="meta">',
        f"<p>Run ID: {esc(m.run_id)} · Created at: {esc(m.created_at)}"
        f" · Content hash: {esc(m.content_hash)}</p>",
        f"<p>Score profile version: {esc(m.score_profile_version)}"
        f" · Provider model: {esc(_val(m.provider_model))}"
        f" · Project: {esc(m.project_id)}"
        f" · Central entity: {esc(_val(m.central_entity))}</p>",
        "</div>",
        f'<p><span class="gate-badge gate-{esc(status)}">{esc(badge_text)}</span></p>',
        f'<p class="generated">{esc(GENERATED_BY_LINE)}</p>',
    ]
    for title, blocks in _sections(report):
        out.append("<section>")
        out.append(f"<h2>{esc(title)}</h2>")
        out.extend(_html_block(b) for b in blocks)
        out.append("</section>")
    out.append("</body>")
    out.append("</html>")
    return "\n".join(out) + "\n"


