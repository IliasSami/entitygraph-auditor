def test_json_is_canonical_bytes(report_a, report_b):
    payload = render_json(report_a)
    assert isinstance(payload, bytes)
    assert payload.startswith(b'{\n  "audit_metadata"')
    data = json.loads(payload)
    keys = list(data)
    assert keys[0] == "audit_metadata"
    assert keys[1] == "gate"
    assert "café".encode("utf-8") in payload  # UTF-8, not \u-escaped
    assert render_json(report_b) != payload


