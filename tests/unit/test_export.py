def _csv_rows(text: str) -> list[list[str]]:
    return list(csv.reader(io.StringIO(text)))


def test_findings_csv_roundtrips_multiline_and_comma_fields(report_a):
    rows = _csv_rows(render_findings_csv(report_a))
    assert len(rows) == 1 + 4 + 5  # header + passage findings + recommendations
    by_id = {r[1]: r for r in rows[1:]}
    assert by_id["pf-3"][5] == (
        "Multi-line\nwhat text with, comma about opening hours near ঢাকা."
    )
    assert by_id["rec-1"][3] == "high"
    assert render_findings_csv(report_a).endswith("\r\n")


def test_entities_csv_roundtrip(report_a):
    rows = _csv_rows(render_entities_csv(report_a))
    assert len(rows) == 1 + 6
    names = [r[1] for r in rows[1:]]
    assert "Café Noir Roastery" in names
    assert "ঢাকা" in names
    header = rows[0]
    e1 = dict(zip(header, next(r for r in rows[1:] if r[0] == "e1"), strict=True))
    assert e1["kind"] == "central"
    assert e1["is_central"] == "true"
    assert e1["occurrence_count"] == "3"


def test_eav_csv_roundtrip(report_a):
    rows = _csv_rows(render_eav_csv(report_a))
    assert len(rows) == 1 + 5
    price = next(r for r in rows[1:] if r[2] == "price_range")
    assert price[3] == ""  # None → empty field
    assert price[4] == "missing"


def test_fanout_csv_roundtrip(report_a):
    rows = _csv_rows(render_fanout_csv(report_a))
    assert len(rows) == 1 + 8
    q1 = next(r for r in rows[1:] if r[0] == "q1")
    assert q1[8] == "covered"
    assert q1[9] == "1.00"
    q6 = next(r for r in rows[1:] if r[0] == "q6")
