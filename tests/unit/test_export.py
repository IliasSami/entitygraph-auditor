def test_render_returns_payload_media_type_filename(report_a):
    payload, media_type, filename = render(report_a, "markdown")
    assert payload == render_markdown(report_a).encode("utf-8")
    assert media_type == "text/markdown"
    assert filename == "audit-run-a.md"


def test_render_all_supported_formats(report_a):
    expected = {
        "markdown": ("text/markdown", "audit-run-a.md"),
        "html": ("text/html", "audit-run-a.html"),
        "json": ("application/json", "audit-run-a.json"),
        "csv": ("application/zip", "audit-run-a.csv.zip"),
    }
    assert set(SUPPORTED_FORMATS) == set(expected)
    for fmt, (media_type, filename) in expected.items():
        payload, mt, name = render(report_a, fmt)
        assert isinstance(payload, bytes)
        assert payload, fmt
        assert (mt, name) == (media_type, filename)


def test_render_unknown_format_raises_value_error(report_a):
    with pytest.raises(ValueError) as excinfo:
        render(report_a, "pdf")
    message = str(excinfo.value)
    for fmt in SUPPORTED_FORMATS:
        assert fmt in message
    assert "'pdf'" in message
